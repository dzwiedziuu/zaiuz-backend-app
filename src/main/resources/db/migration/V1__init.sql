-- V1: początkowy schemat bazy danych (PostgreSQL), wygenerowany przez Hibernate z encji JPA.
-- Wykonywany przez Flyway jeden raz; kolejne zmiany schematu dodawać jako nowe pliki V2__opis.sql itd.

    create table measurement (
        value float(53) not null,
        id bigint generated by default as identity,
        measured_at timestamp(6) with time zone not null,
        sensor_id bigint,
        series_id bigint not null,
        primary key (id)
    );

    create table sensor (
        created_at timestamp(6) with time zone not null,
        id bigint generated by default as identity,
        series_id bigint not null,
        name varchar(100) not null,
        key_hash varchar(255) not null unique,
        primary key (id)
    );

    create table series (
        max_value float(53) not null,
        min_value float(53) not null,
        id bigint generated by default as identity,
        unit varchar(20),
        icon varchar(100),
        name varchar(100) not null,
        color varchar(255) not null,
        primary key (id)
    );

    create table session (
        expires_at timestamp(6) with time zone not null,
        id bigint generated by default as identity,
        user_id bigint not null,
        token_hash varchar(255) not null unique,
        primary key (id)
    );

    create table users (
        id bigint generated by default as identity,
        password_hash varchar(255) not null,
        username varchar(255) not null unique,
        primary key (id)
    );

